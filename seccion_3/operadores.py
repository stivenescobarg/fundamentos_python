# SECCIÓN 3 – Operadores en Python

# Python como calculadora
print(2 + 2)

# Exponenciación
print(2 ** 3)
print(2 ** 3.)
print(2. ** 3)
print(2. ** 3.)

# Multiplicación
print(2 * 3)
print(2 * 3.)
print(2. * 3)
print(2. * 3.)

# División
print(6 / 3)
print(6 / 3.)
print(6. / 3)
print(6. / 3.)

# División entera
print(6 // 3)
print(6 // 3.)
print(6. // 3)
print(6. // 3.)

print(6 // 4)
print(6. // 4)

print(-6 // 4)
print(6. // -4)

# Módulo (residuo)
print(14 % 4)
print(12 % 4.5)

# Suma
print(-4 + 4)
print(-4. + 8)

# Resta y operadores unarios
print(-4 - 4)
print(4. - 8)
print(-1.1)
print(+2)

# Prioridad de operadores
print(2 + 3 * 5)

# Enlazado (izquierda)
print(9 % 6 % 2)

# Exponenciación (derecha)
print(2 ** 2 ** 3)

# Ejemplo importante
print(-3 ** 2)
print(-2 ** 3)
print(-(3 ** 2))

# Expresión con prioridad
print(2 * 3 % 5)

# Expresión con paréntesis
print((5 * ((25 % 13) + 100) / (2 * 13)) // 2)