# LAB: Literales básicos en Python

# Diferencia entre cadena y número
print("2")   # Esto es una cadena (string)
print(2)     # Esto es un número entero (int)

# Enteros
print(123)
print(-100)
print(11_111_111)  # Uso de guion bajo para mejorar legibilidad

# Números octales (base 8)
print(0o123)  # Resultado esperado: 83

# Números hexadecimales (base 16)
print(0x123)  # Resultado esperado: 291

# Números flotantes
print(2.5)
print(-0.4)
print(.4)
print(4.)

# Notación científica
print(3E8)        # 300000000
print(6.62607E-34)

# Python puede cambiar la forma de mostrar números
print(0.0000000000000000000001)

# Cadenas con comillas
print("Me gusta \"Monty Python\"")
print('Me gusta "Monty Python"')

# Uso de escape para apóstrofe
print('I\'m Monty Python.')

# Valores booleanos
print(True)
print(False)

# Reto
print(True > False)
print(True < False)